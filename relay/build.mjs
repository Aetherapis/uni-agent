// Builds dist/worker.bundle.js: worker.js with the helper `export`s removed, so the file has ONLY
// `export default` and can be pasted straight into the Cloudflare dashboard editor.
//   node build.mjs            write dist/worker.bundle.js
//   node build.mjs --check    exit 1 if dist/ is out of date
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";

const src = readFileSync(new URL("./worker.js", import.meta.url), "utf8");
const out = "// GENERATED by relay/build.mjs from worker.js - paste this whole file into the Cloudflare dashboard.\n"
  + src.replace(/^export (async function|function|const)/gm, "$1");
const target = new URL("./dist/worker.bundle.js", import.meta.url);

if (process.argv.includes("--check")) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current !== out) { console.error("relay/dist/worker.bundle.js is out of date: run `node relay/build.mjs`"); process.exit(1); }
} else {
  mkdirSync(new URL("./dist/", import.meta.url), { recursive: true });
  writeFileSync(target, out);
  console.log(`wrote dist/worker.bundle.js (${out.length} bytes)`);
}
